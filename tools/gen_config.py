#!/usr/bin/env python3
"""Generate game/src/config/safezones.js from game/data/midlothian.json.

Every school or college campus (OSM amenity=school/college areas) plus any named building that is a school
(preschools, academies) becomes a weapon-free safe zone. Re-run after re-fetching map data:
    python3 -I tools/gen_config.py
"""
import json, math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "game", "data", "midlothian.json")
OUT = os.path.join(HERE, "..", "game", "src", "config", "safezones.js")
d = json.load(open(DATA))
zones = []
for a in d["areas"]:
    if a["kind"] in ("school", "college"):
        zones.append({"name": a.get("name") or "School campus", "kind": a["kind"], "pts": a["pts"]})
names = {z["name"] for z in zones}
for b in d["buildings"]:
    n = b.get("name") or ""
    if b.get("school") or not re.search(r"\b(school|academy|college|preschool|montessori)\b", n, re.I) or n in names: continue
    cx = sum(p[0] for p in b["pts"]) / len(b["pts"]); cz = sum(p[1] for p in b["pts"]) / len(b["pts"])
    r = max(math.hypot(p[0] - cx, p[1] - cz) for p in b["pts"]) + 25
    zones.append({"name": n, "kind": "school building", "pts": [[round(cx + math.cos(i / 16 * 2 * math.pi) * r, 1), round(cz + math.sin(i / 16 * 2 * math.pi) * r, 1)] for i in range(16)]})
    names.add(n)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("// GENERATED by tools/gen_config.py from data/midlothian.json. Safe to hand-edit; re-running overwrites.\n")
    f.write("// School safe zones: weapons holster, no hostile NPCs, no police response, no wanted level can start,\n")
    f.write("// and no mission may use these as a combat location.\n")
    f.write("export const SAFE_ZONES = " + json.dumps(zones, separators=(",", ":")) + ";\n")
print(f"{len(zones)} safe zones -> {OUT}:", ", ".join(z["name"] for z in zones))
